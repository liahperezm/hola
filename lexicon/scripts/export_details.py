#!/usr/bin/env python3
"""Export pronunciations, example sentences and opposites for the dictionary.

Reads lexicon/data/details/*.txt, one word per line:

    id | pronunciation | example sentence | opposite; opposite

(the opposites column may be empty) and writes src/lib/details.generated.ts.
Hand-written details in dictionary.ts take precedence over these.

    python3 lexicon/scripts/export_details.py && pnpm test
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "lexicon/data/details"
TARGET = ROOT / "src/lib/details.generated.ts"


def main() -> None:
    details: dict[str, dict] = {}
    for path in sorted(SOURCE.glob("*.txt")):
        for n, line in enumerate(path.read_text().splitlines(), 1):
            if not line.strip():
                continue
            parts = [p.strip() for p in line.split("|")]
            if len(parts) != 4:
                raise SystemExit(f"{path.name}:{n}: expected 4 columns, got {len(parts)}")
            word_id, pronunciation, example, opposites = parts
            if word_id in details:
                raise SystemExit(f"{path.name}:{n}: {word_id} is listed twice")
            entry = {"pronunciation": pronunciation, "example": example}
            antonyms = [o.strip() for o in opposites.split(";") if o.strip()]
            if antonyms:
                entry["antonyms"] = antonyms
            details[word_id] = entry
    lines = [
        "// Generated by lexicon/scripts/export_details.py from lexicon/data/details.",
        "// Do not edit by hand.",
        'import type { TermDetail } from "./dictionary";',
        "",
        "export const DETAILS: Record<string, TermDetail> = {",
        *[f"  {json.dumps(k, ensure_ascii=False)}: {json.dumps(v, ensure_ascii=False)}," for k, v in details.items()],
        "};",
        "",
    ]
    TARGET.write_text("\n".join(lines))
    print(f"{len(details)} words -> {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
