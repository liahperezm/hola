// Builds src/lib/accents.generated.ts: words that are only valid with an
// accent, so "plastico" can be written "plástico" in a translation. Words that
// are valid both ways (esta/está, el/él, ano/año) are left out, since only the
// meaning can tell them apart.
//
//   node lexicon/scripts/export_accents.mjs
//
// Source: dictionary-es (the LibreOffice Spanish dictionary, a dev
// dependency), used under its MPL 1.1 option. Only base forms are read, plus
// their plural (flag S) and feminine (flag G) forms.
import { readFileSync, writeFileSync } from "node:fs";

const dic = readFileSync(
  new URL("../../node_modules/dictionary-es/index.dic", import.meta.url),
  "utf8",
)
  .split("\n")
  .slice(1)
  .filter(Boolean);

// Remove accents and diaeresis, keep ñ.
const strip = (w) =>
  w
    .normalize("NFD")
    .replace(/ñ/g, "\u0000")
    .replace(/[̀-ͯ]/g, "")
    .replace(/\u0000/g, "ñ")
    .normalize("NFC");

const ACCENTED_LAST = /[áéíóú]([ns])$/;

function plural(w) {
  if (/[aeiouáéíóú]$/.test(w)) return `${w}s`;
  if (ACCENTED_LAST.test(w)) return `${strip(w)}es`; // camión -> camiones
  if (/z$/.test(w)) return `${w.slice(0, -1)}ces`; // lápiz -> lápices
  return `${w}es`; // árbol -> árboles
}

function forms(stem, flags) {
  const out = new Set([stem]);
  if (flags.includes("G") && /o$/.test(stem)) out.add(`${stem.slice(0, -1)}a`);
  if (flags.includes("S")) for (const f of [...out]) out.add(plural(f));
  return out;
}

const valid = new Set();
const accented = new Set();
const verbs = new Set();
for (const line of dic) {
  const [stem, flags = ""] = line.split("/");
  if (!/^\p{Ll}+$/u.test(stem)) continue; // skip names, abbreviations
  if (/(ar|er|ir)$/.test(stem)) verbs.add(stem.slice(0, -2));
  for (const f of forms(stem, flags)) {
    valid.add(f);
    if (f !== strip(f)) accented.add(f);
  }
}

// The dictionary lists verbs by their infinitive only, so "termino" (from
// terminar) and "bebe" (from beber) look like misspellings of término and
// bebé. Anything that could be a present-tense form of a known verb is left alone.
const ENDINGS = ["o", "as", "a", "amos", "an", "es", "e", "emos", "en", "imos"];
function couldBeVerb(plain) {
  return ENDINGS.some((e) => plain.endsWith(e) && verbs.has(plain.slice(0, -e.length)));
}

// Words people type without ñ: "nino" for niño, "manana" for mañana.
for (const w of valid) if (w.includes("ñ")) accented.add(w);

const byPlain = new Map();
const clash = new Set();
for (const w of accented) {
  const plain = strip(w).replace(/ñ/g, "n");
  if (valid.has(plain) || couldBeVerb(plain)) continue; // "esta", "ano", "termino"
  if (byPlain.has(plain) && byPlain.get(plain) !== w) clash.add(plain);
  byPlain.set(plain, w);
}
for (const c of clash) byPlain.delete(c);

const list = [...byPlain.values()].sort();
const out = [
  "// Generated by lexicon/scripts/export_accents.mjs from dictionary-es",
  "// (LibreOffice Spanish dictionary, MPL 1.1). Words only valid with an accent.",
  "// Do not edit by hand.",
  `export const ACCENTED = ${JSON.stringify(list.join(" "))};`,
  "",
].join("\n");
writeFileSync(new URL("../../src/lib/accents.generated.ts", import.meta.url), out);
console.log(`${list.length} accented forms (${clash.size} clashes left out)`);
