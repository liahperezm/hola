#!/usr/bin/env python3
"""Export the sayings Hola recognizes inside sentences.

Reads lexicon/data/idioms.json (the sayings) and lexicon/data/sayings_es.json
(their meaning in Spanish; only sayings listed there are exported) and writes
src/lib/sayings.generated.ts.

    python3 lexicon/scripts/export_sayings.py && pnpm test
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
IDIOMS = ROOT / "lexicon/data/idioms.json"
MEANINGS = ROOT / "lexicon/data/sayings_es.json"
TARGET = ROOT / "src/lib/sayings.generated.ts"


def main() -> None:
    meanings = json.loads(MEANINGS.read_text())["meanings"]
    out = []
    for text, kind, countries, register, gloss, literal, example, note in json.loads(IDIOMS.read_text())["idioms"]:
        # Sayings of some countries only are dictionary entries (DICHOS in
        # src/lib/dictionary.ts); here go those said the same everywhere.
        if text not in meanings or "ALL" not in countries.split():
            continue
        out.append({
            "text": text,
            "es": meanings[text],
            "en": gloss,
        })
    known = {row[0] for row in json.loads(IDIOMS.read_text())["idioms"]}
    missing = sorted(set(meanings) - known)
    if missing:
        raise SystemExit(f"Meanings for sayings not in idioms.json: {missing}")
    lines = [
        "// Generated by lexicon/scripts/export_sayings.py from lexicon/data/idioms.json",
        "// and lexicon/data/sayings_es.json. Do not edit by hand.",
        'import type { Saying } from "./sayings";',
        "",
        "export const SAYINGS: Saying[] = [",
        *[f"  {json.dumps(s, ensure_ascii=False)}," for s in out],
        "];",
        "",
    ]
    TARGET.write_text("\n".join(lines))
    print(f"{len(out)} sayings -> {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
